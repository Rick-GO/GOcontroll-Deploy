// Make test/fixtures/goco/fixtures.json: the cross-check between src/goco.ts and the
// reference implementation, GOcontroll-Deployment-Tool/tools/goco.py (and keys.py).
//
//   npm run fixtures:goco                                  (Deployment Tool next to GOcontroll-Team)
//   DEPLOYMENT_TOOL=<path to its tools dir> npm run fixtures:goco
//
// 1. Python (`python -I`, scripts/goco-fixtures.py make) builds a fixed test key in every format
//    keys.py reads, a zlib payload, and per App ID an unsigned and a signed container.
// 2. This script signs the same payload with the same key the way Deploy does since 0.7.0: the
//    scope from src/goco.ts (signedScope; Node runs it as it is: no imports, erasable TypeScript),
//    signed by public/js/signing.js (signerFor, signScope) as the browser does, the header put
//    together by src/goco.ts (headerWithSignature). It also makes a key pair as the Key generator
//    does (generateKeyPair).
// 3. Python (scripts/goco-fixtures.py verify) checks every container signed that way with
//    goco.parse_header + goco.verify_signature, and reads the key pair's PEM and public key with
//    keys.py (the files the Key generator downloads).
// The result is committed; test/goco.test.ts checks src/goco.ts against it without Python.
// ECDSA signatures are randomised, so the signed containers differ on every run: that is fine.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { concat, headerWithSignature, sha256, signedScope } from '../src/goco.ts';
import { generateKeyPair, signScope, signerFor } from '../public/js/signing.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tools = process.env.DEPLOYMENT_TOOL || resolve(root, '..', '..', 'GOcontroll-Deployment-Tool', 'tools');
const python = process.env.PYTHON || 'python';
const script = join(root, 'scripts', 'goco-fixtures.py');

const b64 = (bytes) => Buffer.from(bytes).toString('base64');
const unb64 = (s) => new Uint8Array(Buffer.from(s, 'base64'));
const run = (...args) => execFileSync(python, ['-I', script, tools, ...args], { encoding: 'utf-8', maxBuffer: 64 * 1024 * 1024 });

const made = JSON.parse(run('make'));
const signer = await signerFor(made.key.private_b64, made.key.public_hex, 'the fixtures');
const publicKey = unb64(Buffer.from(made.key.public_hex, 'hex').toString('base64'));
const payload = unb64(made.payload_b64);
const digest = await sha256(payload);

const tsSigned = [];
for (const c of made.cases) {
  const scope = signedScope({ appId: c.app_id, version: c.version, compressedSize: payload.length, rawSize: made.raw_size, payloadSha256: digest, publicKey });
  const header = headerWithSignature(scope, await signScope(signer, scope, payload));
  tsSigned.push({ app_id: c.app_id, ts_signed_b64: b64(concat(header, payload)) });
}
const pair = await generateKeyPair();

const dir = mkdtempSync(join(tmpdir(), 'goco-'));
let verified;
try {
  const input = join(dir, 'ts-signed.json');
  writeFileSync(input, JSON.stringify({ cases: tsSigned, key_pair: pair }));
  verified = JSON.parse(run('verify', input));
} finally {
  rmSync(dir, { recursive: true, force: true });
}
if (!verified.key_pair?.pem || !verified.key_pair?.public || verified.cases.some((c) => !c.verified)) throw new Error('Python did not verify the output');

const out = {
  _about: 'Generated by scripts/goco-fixtures.mjs from GOcontroll-Deployment-Tool/tools/goco.py + keys.py; do not edit.',
  ...made,
  cases: made.cases.map((c, i) => ({
    ...c,
    ts_signed_b64: tsSigned[i].ts_signed_b64,
    ts_signed_python_header: verified.cases[i].header,
    ts_signed_verified_by_python: verified.cases[i].verified,
  })),
  // The Key generator's pair (not committed: only whether keys.py read it): PEM → the same scalar as
  // the base64 value, and the public key keys.py derives from it = the .pub.
  browser_key_pair_read_by_python: verified.key_pair,
};
writeFileSync(join(root, 'test', 'fixtures', 'goco', 'fixtures.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(`fixtures.json: ${out.cases.length} App IDs, every container signed the browser's way verified by goco.py, the key pair read by keys.py`);
